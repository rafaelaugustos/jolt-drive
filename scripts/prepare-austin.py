"""Build the offline scene from an OpenStreetMap API XML extract.

Usage: python3 scripts/prepare-austin.py /tmp/jolt-austin.osm
Source: https://api.openstreetmap.org/api/0.6/map?bbox=-97.7465,30.2625,-97.7405,30.2700
"""
import json
import math
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
nodes = {n.attrib['id']: (float(n.attrib['lat']), float(n.attrib['lon'])) for n in root.findall('node')}
origin = (30.2657, -97.7437)
mx = 111320 * math.cos(math.radians(origin[0]))
def local(p):
    return [round((p[1] - origin[1]) * mx, 2), round(-(p[0] - origin[0]) * 111320, 2)]
def number(v, fallback):
    match = re.match(r'^([\d.]+)', v or '')
    return float(match[1]) if match else fallback

buildings, roads, congress = [], [], {}
for way in root.findall('way'):
    tags = {t.attrib['k']: t.attrib['v'] for t in way.findall('tag')}
    coords = [nodes[n.attrib['ref']] for n in way.findall('nd')]
    pts = [local(p) for p in coords]
    if not any(abs(p[0]) < 380 and abs(p[1]) < 550 for p in pts):
        continue
    if tags.get('building') and len(pts) > 3 and pts[0] == pts[-1]:
        levels = number(tags.get('building:levels'), 4 if tags.get('building') in ('commercial', 'office', 'hotel') else 2)
        height = number(tags.get('height'), levels * 3.6)
        buildings.append({'id': int(way.attrib['id']), 'height': round(height, 1), 'surveyedHeight': 'height' in tags, 'points': pts[:-1]})
    if tags.get('highway') in ('primary', 'secondary', 'tertiary', 'residential', 'unclassified', 'living_street'):
        width = max(8, min(24, number(tags.get('lanes'), 2) * 3.1))
        roads.append({'name': tags.get('name', ''), 'width': round(width, 1), 'points': pts})
        if tags.get('name') == 'Congress Avenue':
            for p in coords:
                if 30.2643199 <= p[0] <= 30.2670367:
                    congress[p] = p

data = {'origin': origin, 'buildings': buildings, 'roads': roads, 'route': sorted(congress.values())}
target = Path(__file__).resolve().parents[1] / 'src/components/summon/austin-data.ts'
target.write_text('// © OpenStreetMap contributors. ODbL 1.0. Extract: 2026-10-24.\n'
                  '// https://www.openstreetmap.org/copyright — see AUSTIN-DATA-LICENSE.txt.\n'
                  '// Generated by scripts/prepare-austin.py. Missing building heights are estimates.\n'
                  'export const austin = ' + json.dumps(data, separators=(',', ':')) + '\n')
print(f'{len(buildings)} buildings, {len(roads)} road segments, {len(congress)} route points → {target}')
